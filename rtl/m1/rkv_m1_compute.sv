// 固定 Qwen3 配置的 openTPU 计算包装；不含 DPI、DDR IP 或板级引脚假设。
// 复用 vendor/openTPU 91df4109 的 slice / collective；参数来自统一生成包。
module rkv_m1_compute (
    input logic clk,
    input logic clk_f,
    input logic cold_reset,
    input logic npu_reset,
    input logic [31:0] npu_args [8],
    input logic loader_start,
    input logic [31:0] loader_addr,
    input logic [31:0] loader_count,
    output logic loader_busy,
    input logic wr_idle,
    input logic rd_idle,
    output logic halted,
    output logic error,
    output logic a_inval,
    output logic [31:0] icount,
    input logic dump,
    output logic a_req,
    output logic a_we,
    output logic [31:0] a_addr,
    output logic [31:0] a_wdata,
    output logic [3:0] a_be,
    input logic a_rdy,
    input logic a_rvalid,
    input logic [255:0] a_rdata,
    output logic sw_req,
    output logic [31:0] sw_addr,
    output logic [31:0] sw_wdata,
    output logic [3:0] sw_be,
    input logic sw_rdy,
    output logic b_req,
    output logic b_we,
    output logic b_tag,
    output logic b_par,
    output logic [31:0] b_addr,
    output logic [1023:0] b_wdata,
    output logic [31:0] b_wmask,
    input logic b_rdy,
    input logic b_rvalid,
    input logic b_rtag,
    input logic [1023:0] b_rdata
);
    import otpu_pkg::*;
    import rkv_m1_layout_pkg::*;
    logic [0:0] coll_req;
    cmd_t coll_cmd [1];
    logic coll_ack;
    logic [0:0] coll_gl;
    logic [0:0][7:0] coll_ren;
    logic [0:0][7:0][31:0] coll_raddr;
    logic [0:0][7:0][31:0] coll_rdata;
    logic [7:0] coll_wen;
    logic [7:0][31:0] coll_waddr;
    logic [7:0][31:0] coll_wdata;
    otpu_slice #(
        .SID(0),
        .S(CFG_S),
        .D(CFG_D),
        .MCOLS(CFG_MCOLS),
        .ACT_BLOCKS(CFG_ACT_BLOCKS),
        .TMEM_WORDS(CFG_TMEM_WORDS),
        .IMEM_WORDS(CFG_IMEM_WORDS),
        .LANES(CFG_LANES),
        .ACT_ROWS(CFG_ACT_ROWS),
        .SEQ_WC(1'(CFG_SEQ_WC)),
        .FIFO_DEPTH(CFG_FIFO_DEPTH),
        .WIN(CFG_WIN),
        .RPB(CFG_RPB),
        .WPB(CFG_WPB),
        .MXU_IMPL(CFG_MXU_IMPL),
        .MXU_CL(CFG_MXU_CL),
        .MXU_E(CFG_MXU_E),
        .QUANT_XD(CFG_QUANT_XD),
        .VPU_CL(CFG_VPU_CL),
        .ULANES(CFG_ULANES),
        .TMEM_IMPL(CFG_TMEM_IMPL),
        .TMEM_RQ(1'(CFG_TMEM_RQ)),
        .TMEM_NCP(CFG_TMEM_NCP),
        .TMEM_NSB(CFG_TMEM_NSB),
        .TMEM_SBP(CFG_TMEM_SBP),
        .TMEM_SBH(CFG_TMEM_SBH),
        .TMEM_RPL(1'(CFG_TMEM_RPL)),
        .TMEM_TDP(1'(CFG_TMEM_TDP)),
        .TMEM_GST(1'(CFG_TMEM_GST)),
        .TMEM_PMP(CFG_TMEM_PMP),
        .TMEM_PRK(CFG_TMEM_PRK),
        .TMEM_SDM(CFG_TMEM_SDM)
    ) compute (
        .clk(clk),
        .clk_f(clk_f),
        .sys_rst(cold_reset),
        .rst(npu_reset),
        .rinit(npu_args),
        .ld_start(loader_start),
        .ld_addr(loader_addr),
        .ld_n(loader_count),
        .ld_busy(loader_busy),
        .wr_idle(wr_idle),
        .rd_idle(rd_idle),
        .a_addr(a_addr),
        .a_be(a_be),
        .a_rdata(a_rdata),
        .a_rdy(a_rdy),
        .a_req(a_req),
        .a_rvalid(a_rvalid),
        .a_wdata(a_wdata),
        .a_we(a_we),
        .b_addr(b_addr),
        .b_rdata(b_rdata),
        .b_rdy(b_rdy),
        .b_req(b_req),
        .b_rtag(b_rtag),
        .b_rvalid(b_rvalid),
        .b_tag(b_tag),
        .b_wdata(b_wdata),
        .b_we(b_we),
        .b_wmask(b_wmask),
        .sw_addr(sw_addr),
        .sw_be(sw_be),
        .sw_rdy(sw_rdy),
        .sw_req(sw_req),
        .sw_wdata(sw_wdata),
        .b_par(b_par),
        .coll_req(coll_req[0]),
        .coll_cmd(coll_cmd[0]),
        .coll_ack(coll_ack),
        .coll_ren(coll_ren[0]),
        .coll_raddr(coll_raddr[0]),
        .coll_rdata(coll_rdata[0]),
        .coll_wen(coll_wen),
        .coll_waddr(coll_waddr),
        .coll_wdata(coll_wdata),
        .coll_gnt_local(coll_gl[0]),
        .coll_gnt(coll_gl[0]),
        .halted(halted),
        .error(error),
        .wait_to(),
        .a_inval(a_inval),
        .icount(icount),
        .pf(),
        .dump(dump)
    );
    otpu_coll #(
        .S(CFG_S),
        .LANES(CFG_LANES)
    ) collective (
        .clk(clk),
        .rst(npu_reset),
        .req(coll_req),
        .cmds(coll_cmd),
        .gnt(coll_gl[0]),
        .ack(coll_ack),
        .r_en(coll_ren),
        .r_addr(coll_raddr),
        .r_data(coll_rdata),
        .w_en(coll_wen),
        .w_addr(coll_waddr),
        .w_data(coll_wdata)
    );
endmodule
